export const presetById = (id: string): CharacterSpec | undefined =>
  PRESETS.find((preset) => preset.id === id)

function p(
  id: string,
  name: string,
  palette: CharacterSpec['palette'],
  marks: CharacterSpec['marks'],
  noFeet = false,
): CharacterSpec {
  return { version: 1, base: 'bubble-16', id, name, palette, marks, ...(noFeet && { noFeet }) }
}
